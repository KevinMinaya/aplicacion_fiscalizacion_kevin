package com.example.producto_api_kevin;

public class Producto {

    private int id;
    private String title;
    private double price;
    private String category;

    public int getId() {
        return id;
    }

    public String getTitle() {
        return title;
    }

    public double getPrice() {
        return price;
    }

    public String getCategory() {
        return category;
    }
}